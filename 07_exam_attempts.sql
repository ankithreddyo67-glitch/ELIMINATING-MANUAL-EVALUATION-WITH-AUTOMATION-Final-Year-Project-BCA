CREATE TABLE IF NOT EXISTS exam_attempts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    exam_id BIGINT UNSIGNED NOT NULL,
    student_id BIGINT UNSIGNED NOT NULL,
    status VARCHAR(255) NOT NULL DEFAULT 'IN_PROGRESS' CHECK(status IN ('IN_PROGRESS', 'SUBMITTED', 'EVALUATED', 'PUBLISHED')),
    started_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_at DATETIME,
    evaluated_at DATETIME,
    objective_score DOUBLE NOT NULL DEFAULT 0.0,
    subjective_score DOUBLE NOT NULL DEFAULT 0.0,
    total_score DOUBLE NOT NULL DEFAULT 0.0,
    max_score DOUBLE NOT NULL DEFAULT 0.0,
    percentage DOUBLE NOT NULL DEFAULT 0.0,
    grade VARCHAR(255) NOT NULL DEFAULT '-',
    passed TINYINT NOT NULL DEFAULT 0,
    integrity_score DOUBLE NOT NULL DEFAULT 100.0,
    risk_level VARCHAR(255) NOT NULL DEFAULT 'CLEAR',
    warning_count INT NOT NULL DEFAULT 0,
    termination_reason TEXT NOT NULL DEFAULT (''),
    faculty_remarks TEXT NOT NULL DEFAULT (''),
    FOREIGN KEY (exam_id) REFERENCES exams (id) ON DELETE CASCADE,
    FOREIGN KEY (student_id) REFERENCES users (id) ON DELETE CASCADE,
    KEY ix_attempts_exam_status (exam_id, status),
    KEY ix_attempts_student_exam (student_id, exam_id)
) ENGINE = InnoDB;
